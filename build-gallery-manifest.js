const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = __dirname;
const galleryRoot = path.join(root, 'gallery');
const manifestPath = path.join(galleryRoot, 'gallery.js');
const imageExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif']);

function readExistingEntries() {
  if (!fs.existsSync(manifestPath)) return [];
  const source = fs.readFileSync(manifestPath, 'utf8');
  const context = { window: {} };
  vm.runInNewContext(source, context);
  return Array.isArray(context.window.galleryData) ? context.window.galleryData : [];
}

function collectImages(directory, relativeDirectory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(function (entry) {
    const absolutePath = path.join(directory, entry.name);
    const relativePath = path.join(relativeDirectory, entry.name);
    if (entry.isDirectory()) return collectImages(absolutePath, relativePath);
    return imageExtensions.has(path.extname(entry.name).toLowerCase()) ? [relativePath] : [];
  });
}

function toWebPath(relativePath) {
  return relativePath.split(path.sep).join('/');
}

const existingEntries = readExistingEntries();
const existingByPath = new Map(existingEntries.map(function (entry) { return [entry.image, entry]; }));
const imagePaths = fs.existsSync(galleryRoot)
  ? collectImages(galleryRoot, 'gallery').filter(function (file) {
    return file.split(path.sep)[1] && /^\d{4}$/.test(file.split(path.sep)[1]);
  })
  : [];

const entries = imagePaths.map(function (file) {
  const image = toWebPath(file);
  const parts = image.split('/');
  const folder = parts.slice(1, -1).join('/');
  const existing = existingByPath.get(image);
  const defaultLabel = parts[parts.length - 2] || parts[parts.length - 1];
  return {
    image,
    alt: existing && existing.alt ? existing.alt : defaultLabel,
    caption: existing && existing.caption ? existing.caption : defaultLabel,
    folder,
    folderLabel: parts[parts.length - 2] || defaultLabel
  };
}).sort(function (left, right) {
  return left.folder.localeCompare(right.folder) || left.image.localeCompare(right.image, undefined, { numeric: true });
});

const output = '// Generated by build-gallery-manifest.js. Edit captions in this file after adding images.\n'
  + 'window.galleryData = ' + JSON.stringify(entries, null, 2) + ';\n';
fs.writeFileSync(manifestPath, output);
console.log(`Gallery manifest updated: ${entries.length} images across ${new Set(entries.map(function (entry) { return entry.folder; })).size} folders.`);
